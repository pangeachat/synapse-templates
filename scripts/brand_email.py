"""Generate each sender's copy of the brand email layout from this repo's templates, or check one.

    python scripts/brand_email.py write module PATH       # PATH: a synapse-pangea-chat checkout
    python scripts/brand_email.py check engagement PATH   # PATH: an engagement checkout
    python scripts/brand_email.py selftest                # generate every copy in memory

``--ref REF`` reads the source at a git ref of this repo instead of the working tree, so a check can
compare against main whatever is checked out. The design is
.github/instructions/brand-email-layout.instructions.md.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SOURCES = ("_brand_email_base.html", "_brand_email_footer.html", "_brand_cta_button.html")
SOURCE_HEADER = re.compile(r"\A\{#.*?#\}\n", re.S)
MODULE_FOLDERS = ("synapse_pangea_chat/notice_delivery/templates", "synapse_pangea_chat/email_invite/templates")
ENGAGEMENT_SHELL = "engagement/templates/brand_email.html"
ENGAGEMENT_BUTTON = "engagement/templates/brand_cta_button.html"
# The engagement runner fills these itself; Synapse fills the double-brace ones when it sends.
ENGAGEMENT_SLOTS = {
    "lang": "[[LANG]]",
    "title": "[[TITLE]]",
    "receiving_reason": "[[FOOTER_REASON]]",
    "unsubscribe_url": "{{unsubscribe_url}}",
    "postal_address": "{{postal_address}}",
}


def read_sources(ref: str | None) -> dict[str, str]:
    if ref is None:
        return {name: (REPO / "templates" / name).read_text(encoding="utf-8") for name in SOURCES}
    out = {}
    for name in SOURCES:
        shown = subprocess.run(["git", "-C", str(REPO), "show", f"{ref}:templates/{name}"], capture_output=True, text=True)
        if shown.returncode != 0:
            raise SystemExit(f"cannot read templates/{name} at {ref}: {shown.stderr.strip()}")
        out[name] = shown.stdout
    return out


def generated_note(name: str) -> str:
    return f"Generated by synapse-templates scripts/brand_email.py from templates/{name}. Do not edit: change the source there and regenerate."


def module_copies(src: dict[str, str]) -> dict[str, str]:
    """The module renders these with its own Jinja, so the copies are the source with only the header changed."""
    out = {}
    for name, text in src.items():
        body, n = SOURCE_HEADER.subn("", text, count=1)
        if n != 1:
            raise SystemExit(f"templates/{name} has lost its header comment")
        for folder in MODULE_FOLDERS:
            out[f"{folder}/{name}"] = "{# " + generated_note(name) + " #}\n" + body
    return out


def engagement_copies(src: dict[str, str]) -> dict[str, str]:
    """The runner fills its shell by string replacement, so the source is rendered with its placeholders in the slots."""
    import jinja2

    shell = (
        '{% extends "_brand_email_base.html" %}{% block content %}\n'
        '            <tr>\n              <td class="body-content" style="padding: 36px 40px 24px;">\n[[CONTENT]]\n              </td>\n            </tr>\n'
        "{% endblock %}"
    )
    button = '{% from "_brand_cta_button.html" import cta_button %}{{ cta_button("[[URL]]", "[[LABEL]]", outlook=false) }}'
    env = jinja2.Environment(loader=jinja2.DictLoader({**src, "shell": shell, "button": button}), autoescape=True, undefined=jinja2.StrictUndefined)
    html = env.get_template("shell").render(**ENGAGEMENT_SLOTS).lstrip()
    if not html.startswith("<!doctype html>"):
        raise SystemExit("the rendered shell does not start with the doctype")
    for slot in (*ENGAGEMENT_SLOTS.values(), "[[CONTENT]]"):
        if html.count(slot) != 1:
            raise SystemExit(f"the rendered shell has {html.count(slot)} of the slot {slot}, expected exactly one")
    html = html.replace("<head>", "<head>\n    <!-- " + generated_note("_brand_email_base.html") + " -->", 1)
    html = "\n".join(line.rstrip() for line in html.splitlines()) + "\n"
    rendered_button = env.get_template("button").render().strip()
    return {
        ENGAGEMENT_SHELL: html,
        ENGAGEMENT_BUTTON: "<!-- " + generated_note("_brand_cta_button.html") + " -->\n" + rendered_button + "\n",
    }


CONSUMERS = {"module": module_copies, "engagement": engagement_copies}


def render_own_emails() -> int:
    """Render every email in this repo that extends the layout, so a source change that breaks one fails here."""
    import jinja2

    templates = REPO / "templates"
    env = jinja2.Environment(loader=jinja2.ChoiceLoader([jinja2.FileSystemLoader(str(templates)), jinja2.DictLoader({"style.css": ""})]), autoescape=True)
    env.filters["format_ts"] = lambda value, fmt: ""
    names = sorted(p.name for p in templates.glob("*.html") if '{% extends "_brand_email_base.html" %}' in p.read_text(encoding="utf-8"))
    for name in names:
        env.get_template(name).render(app_name="Pangea Chat")
    return len(names)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("action", choices=("write", "check", "selftest"))
    parser.add_argument("consumer", nargs="?", choices=tuple(CONSUMERS))
    parser.add_argument("path", nargs="?", type=Path)
    parser.add_argument("--ref", help="read the source at this git ref of synapse-templates")
    args = parser.parse_args()
    src = read_sources(args.ref)
    if args.action == "selftest":
        for name, make in CONSUMERS.items():
            print(f"{name}: {len(make(src))} files generated")
        print(f"synapse-templates: {render_own_emails()} emails on the layout rendered")
        return
    if args.consumer is None or args.path is None:
        parser.error(f"{args.action} needs a consumer and the path of its checkout")
    copies = CONSUMERS[args.consumer](src)
    if args.action == "write":
        for rel, text in copies.items():
            (args.path / rel).parent.mkdir(parents=True, exist_ok=True)
            (args.path / rel).write_text(text, encoding="utf-8")
        print(f"wrote {len(copies)} brand email files into {args.consumer}")
        return
    stale = [rel for rel, text in copies.items() if not (args.path / rel).exists() or (args.path / rel).read_text(encoding="utf-8") != text]
    if stale:
        print("The brand email layout differs from synapse-templates" + (f" at {args.ref}" if args.ref else "") + ":", file=sys.stderr)
        for rel in stale:
            print(f"  {rel}", file=sys.stderr)
        print(f"Regenerate: python <synapse-templates>/scripts/brand_email.py write {args.consumer} <this checkout>", file=sys.stderr)
        raise SystemExit(1)
    print(f"{args.consumer}: the brand email layout matches synapse-templates" + (f" at {args.ref}" if args.ref else ""))


if __name__ == "__main__":
    main()
